test("new windows discard pending old logs without closing the dialog", async ({ page, request }) => {
  const { streamId } = await (await request.post(`${api}/streams`)).json()
  const add = async (t: number, itemId: string) => expect((await request.post(`${api}/streams/${streamId}/transactions`, { data: { id: `live-${t}`, items: [{ itemId, quantity: 1, weight: 1 }] } })).ok()).toBe(true)
  for (let t = 1; t <= 4; t++) await add(t, "A")
  await page.addInitScript(id => localStorage.setItem("cartlens.streamId", id), streamId)
  let release!: () => void
  let captured!: () => void
  let delivered!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const oldCaptured = new Promise<void>(resolve => { captured = resolve })
  const oldDelivered = new Promise<void>(resolve => { delivered = resolve })
  let holdFirst = true
  await page.route("**/audit/FWUDS_CT?**", async route => {
    if (!holdFirst) return route.continue()
    holdFirst = false
    try {
      const response = await route.fetch()
      captured()
      await gate
      await route.fulfill({ response })
    } catch { /* A retired window's request is expected to be aborted. */ }
    finally { captured(); delivered() }
  })
  try {
    await page.goto("/")
    await page.getByRole("button", { name: "FWUDS-CT", exact: true }).click()
    await page.getByRole("button", { name: "Audit log", exact: true }).click()
    await oldCaptured
    const dialog = auditDialog(page, "CT")
    await expect(dialog.getByRole("status")).toContainText("Đang tải audit log")
    await add(5, "X"); await add(6, "X")
    await expect(dialog).toHaveAccessibleName("Audit log · FWUDS-CT")
    await expect(dialog.getByTestId("audit-window")).toHaveAttribute("data-window-id", "2")
    await expect(dialog.getByTestId("audit-sample")).toHaveCount(0)
    await add(7, "Y"); await add(8, "Y")
    await expect(dialog).toHaveAccessibleName("Audit log · FWUDS-CT")
    await expect(dialog.getByTestId("audit-window")).toHaveAttribute("data-window-id", "3")
    await expect(dialog.getByTestId("audit-sample")).toHaveCount(0)
    release(); await oldDelivered
    await expect(dialog).toHaveAccessibleName("Audit log · FWUDS-CT")
    await expect(dialog.getByTestId("audit-window")).toHaveAttribute("data-window-id", "3")
    await expect(dialog.getByTestId("audit-sample")).toHaveCount(3)
    await expect(dialog.getByTestId("audit-sample").filter({ hasText: "{A}" })).toHaveCount(0)
  } finally { release() }
})

