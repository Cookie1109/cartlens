test("hidden audit suspends fetching and resumes at the latest window", async ({ page, request }) => {
  const { streamId } = await (await request.post(`${api}/streams`)).json()
  const add = async (t: number) => request.post(`${api}/streams/${streamId}/transactions`, { data: { id: `visibility-${t}`, items: [{ itemId: "A", quantity: 1, weight: 1 }] } })
  for (let t = 1; t <= 4; t++) expect((await add(t)).ok()).toBe(true)
  await page.addInitScript(id => localStorage.setItem("cartlens.streamId", id), streamId)
  const urls: string[] = []
  page.on("request", req => { if (req.url().includes("/audit/")) urls.push(req.url()) })
  await page.goto("/")
  await page.getByRole("button", { name: "FWUDS-CT", exact: true }).click()
  await page.getByRole("button", { name: "Audit log", exact: true }).click()
  const dialog = auditDialog(page, "CT")
  await expect(dialog.getByTestId("audit-sample")).toHaveCount(1)
  await page.evaluate(() => { Object.defineProperty(document, "hidden", { value: true, configurable: true }); document.dispatchEvent(new Event("visibilitychange")) })
  for (let t = 5; t <= 8; t++) expect((await add(t)).ok()).toBe(true)
  await expect(dialog).toHaveAccessibleName("Audit log · FWUDS-CT")
  await expect(dialog.getByTestId("audit-window")).toHaveAttribute("data-window-id", "3")
  await expect(dialog.getByTestId("audit-sample")).toHaveCount(0)
  // Wait beyond the throttle interval to prove hidden notifications issue no HTTP.
  await page.waitForTimeout(1200)
  expect(urls).toHaveLength(1)
  await page.evaluate(() => { Object.defineProperty(document, "hidden", { value: false, configurable: true }); document.dispatchEvent(new Event("visibilitychange")) })
  await expect(dialog.getByTestId("audit-sample")).toHaveCount(1)
  expect(urls).toHaveLength(2)
})

