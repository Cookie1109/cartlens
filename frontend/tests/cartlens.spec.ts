import { test,expect } from "@playwright/test"
const api = process.env.CARTLENS_E2E_API || "http://localhost:8081/api/v1"
test.afterEach(async ({page,request}) => {
  const id = await page.evaluate(() => localStorage.getItem("cartlens.streamId")).catch(() => null)
  if (id) {
    const response = await request.get(`${api}/streams/${id}/replay`)
    if (response.status() === 200) {
      const job = await response.json()
      if (["RUNNING","PAUSED","PAUSING","STOPPING"].includes(job.state)) await request.post(`${api}/streams/${id}/replay/stop`)
    }
  }
})
