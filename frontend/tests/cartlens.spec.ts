test("chosen algorithm mines arriving panes and updates the UI without a run request", async ({ page,request }) => {
  const created = await request.post(`${api}/streams`)
  const { streamId } = await created.json()
  await page.addInitScript(id => localStorage.setItem("cartlens.streamId",id),streamId)
  const runRequests: string[] = []
  page.on("request",request => { if (request.method() === "POST" && request.url().includes("/runs")) runRequests.push(request.url()) })
  await page.goto("/")
  await expect(page.getByRole("button",{name:"Stream mới"})).toBeEnabled()
  await page.getByRole("button",{name:"Khai phá",exact:true}).click()
  await page.getByLabel("Kích thước pane").fill("2")
  await page.getByLabel("Số pane trong window").fill("2")
  await page.getByLabel("Ngưỡng minWus").fill("1")
  await page.getByRole("radio",{name:/FWUDS-CT/}).check()
  await page.getByRole("button",{name:"Lưu cấu hình",exact:true}).click()
  await expect(page.getByText(/Thuật toán đang áp dụng: FWUDS-CT/)).toBeVisible()
  const initial = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  expect(initial.latestRun).toBeNull()
  const session = initial.configuration.sessionId
  await page.getByRole("button",{name:"Giao dịch",exact:true}).click()
  await page.getByLabel("Tốc độ giao dịch/giây").fill("5")
  await page.getByLabel("Số giao dịch muốn đọc").fill("40")
  await page.getByRole("button",{name:"Bắt đầu Chainstore",exact:true}).click()
  // The table starts empty and fills while replay is running, without a manual refresh.
  await expect(page.locator("tbody tr").first().locator("td").first()).toHaveText("1")
  expect((await (await request.get(`${api}/streams/${streamId}/replay`)).json()).state).toBe("RUNNING")
  await page.getByRole("button",{name:"Kết quả",exact:true}).click()
  await expect.poll(async () => (await (await request.get(`${api}/streams/${streamId}/overview`)).json()).latestRun?.windowId ?? 0).toBeGreaterThan(0)
  await expect(page.getByTestId("stream-live-status").getByText("FWUDS-CT",{exact:true})).toBeVisible()
  const first = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  await expect.poll(async () => (await (await request.get(`${api}/streams/${streamId}/overview`)).json()).latestRun?.windowId ?? 0).toBeGreaterThan(first.latestRun.windowId)
  await expect.poll(async () => (await (await request.get(`${api}/streams/${streamId}/replay`)).json()).state,{timeout:20000}).toBe("COMPLETED")
  await expect(page.getByText("#19",{exact:true})).toBeVisible()
  const final = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  expect(final.latestRun.algorithm).toBe("FWUDS_CT")
  expect(final.configuration.sessionId).toBe(session)
  expect(final.metrics.processedTransactions).toBe(40)
  expect(final.metrics.bufferedTransactions).toBe(0)
  expect(runRequests).toEqual([])
})

test("pause, edit, apply, continue and weight restart preserve run snapshots and checkpoints", async ({ page,request }) => {
  const { streamId } = await (await request.post(`${api}/streams`)).json()
  await page.addInitScript(id => localStorage.setItem("cartlens.streamId",id),streamId)
  const errors: string[] = []; page.on("pageerror",error => errors.push(error.message))
  const runRequests: string[] = []
  page.on("request",r => { if (r.method() === "POST" && r.url().includes("/runs")) runRequests.push(r.url()) })
  await page.goto("/")
  await expect(page.getByRole("button",{name:"Stream mới"})).toBeEnabled()
  await page.getByRole("button",{name:"Khai phá",exact:true}).click()
  await page.getByRole("radio",{name:"FWUDS-CT",exact:true}).check()
  await page.getByLabel("Kích thước pane").fill("2")
  await page.getByLabel("Số pane trong window").fill("2")
  await page.getByLabel("Ngưỡng minWus").fill("1")
  await page.getByLabel("Tốc độ giao dịch/giây").fill("10")
  await page.getByLabel("Số giao dịch muốn đọc").fill("80")
  await page.getByRole("button",{name:"Bắt đầu Chainstore",exact:true}).click()
  await expect(page.getByLabel("Kích thước pane")).toBeDisabled()
  await expect(page.getByRole("combobox",{name:"Trọng số",exact:true})).toBeDisabled()
  const running = await (await request.get(`${api}/streams/${streamId}/replay`)).json()
  expect(running.request.algorithm).toBe("FWUDS_CT")
  expect(running.request.paneSize).toBe(2)
  await expect.poll(async () => (await (await request.get(`${api}/streams/${streamId}/overview`)).json()).transactionCount).toBeGreaterThanOrEqual(9)
  await page.getByRole("button",{name:"Tạm dừng",exact:true}).click()
  await expect(page.getByText("Đã tạm dừng",{exact:true})).toBeVisible()
  const before = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  await page.getByRole("radio",{name:"FWUDS-DWT",exact:true}).check()
  await page.getByLabel("Kích thước pane").fill("3")
  await page.getByLabel("Số pane trong window").fill("3")
  await page.getByLabel("Ngưỡng minWus").fill("0.9")
  await expect(page.getByRole("button",{name:"Tiếp tục",exact:true})).toBeDisabled()
  await page.waitForTimeout(1200)
  await page.getByRole("button",{name:"Giao dịch",exact:true}).click()
  await expect(page.getByLabel("Kích thước pane")).toHaveValue("3")
  await page.getByRole("button",{name:"Áp dụng",exact:true}).click()
  await expect(page.getByTestId("run-configuration")).toContainText("phiên bản 2")
  await expect(page.getByRole("button",{name:"Tiếp tục",exact:true})).toBeEnabled()
  const applied = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  expect(applied.transactionCount).toBe(before.transactionCount)
  expect(applied.configuration.algorithm).toBe("FWUDS_DWT")
  expect(applied.configuration.sessionId).not.toBe(before.configuration.sessionId)
  expect(applied.metrics.bufferedTransactions).toBe(before.transactionCount % 3)
  const oldHistory = await (await request.get(`${api}/streams/${streamId}/results?sessionId=${before.configuration.sessionId}`)).json()
  expect(oldHistory.length).toBeGreaterThan(0)
  await page.reload()
  await expect(page.getByRole("button",{name:"Stream mới"})).toBeEnabled()
  await page.getByRole("button",{name:"Giao dịch",exact:true}).click()
  await expect(page.getByLabel("Kích thước pane")).toHaveValue("3")
  await expect(page.getByTestId("run-configuration")).toContainText("FWUDS-DWT")
  await page.getByRole("button",{name:"Tiếp tục",exact:true}).click()
  await expect.poll(async () => (await (await request.get(`${api}/streams/${streamId}/overview`)).json()).transactionCount).toBeGreaterThan(before.transactionCount + 3)
  await page.getByRole("button",{name:"Tạm dừng",exact:true}).click()
  await expect(page.getByText("Đã tạm dừng",{exact:true})).toBeVisible()
  const checkpoint = await (await request.get(`${api}/streams/${streamId}/overview`)).json()
  await page.getByRole("combobox",{name:"Trọng số",exact:true}).selectOption("SYNTHETIC_BATCH")
  await page.getByLabel("Tốc độ giao dịch/giây").fill("0")
  await page.getByLabel("Số giao dịch muốn đọc").fill("20")
  await expect(page.getByLabel("Sau khi áp dụng")).toHaveValue("RESTART")
  await page.getByRole("button",{name:"Áp dụng",exact:true}).click()
  await expect(page.getByRole("button",{name:"Restart",exact:true})).toBeEnabled()
  const nextId = await page.evaluate(() => localStorage.getItem("cartlens.streamId"))
  expect(nextId).not.toBe(streamId)
  expect((await (await request.get(`${api}/streams/${nextId}/overview`)).json()).transactionCount).toBe(0)
  expect((await (await request.get(`${api}/streams/${streamId}/overview`)).json()).transactionCount).toBe(checkpoint.transactionCount)
  await page.screenshot({path:"../tmp/ui-run-configuration-paused.png",fullPage:true})
  await page.getByRole("button",{name:"Restart",exact:true}).click()
  await expect(page.getByText("Hoàn tất",{exact:true})).toBeVisible()
  const final = await (await request.get(`${api}/streams/${nextId}/overview`)).json()
  expect(final.transactionCount).toBe(20)
  expect(final.latestRun.algorithm).toBe("FWUDS_DWT")
  const tx = await (await request.get(`${api}/streams/${nextId}/transactions`)).json()
  expect(tx[0].id).toBe("1")
  expect(new Set(tx.map((t: {id:string}) => t.id)).size).toBe(20)
  expect(errors).toEqual([]); expect(runRequests).toEqual([])
})
